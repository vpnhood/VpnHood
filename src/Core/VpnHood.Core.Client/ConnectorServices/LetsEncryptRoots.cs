    private static readonly X509Certificate2Collection Roots = Load();

    // the chain built again with these roots as its only trust, the rest of its policy as it was
    public static bool IsChainTrusted(X509Certificate certificate, X509Chain chain)
    {
        using var leaf = X509CertificateLoader.LoadCertificate(certificate.GetRawCertData());
        using var rootChain = new X509Chain();
        rootChain.ChainPolicy = chain.ChainPolicy.Clone();
        rootChain.ChainPolicy.TrustMode = X509ChainTrustMode.CustomRootTrust;
        rootChain.ChainPolicy.CustomTrustStore.AddRange(Roots);
        var ret = rootChain.Build(leaf);
        foreach (var element in rootChain.ChainElements)
            element.Certificate.Dispose();

        return ret;
    }

    private static X509Certificate2Collection Load()
