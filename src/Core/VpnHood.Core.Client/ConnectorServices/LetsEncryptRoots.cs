// Let's Encrypt's roots, trusted beside the system's when a server's chain fails only for want of its root: Android
// 7.0 lacks ISRG Root X1, Android before 14 lacks X2, and no system has the 2025 roots YE and YR yet. A server on
// .NET sends its chain only up to the first root its own system trusts, X2 on Ubuntu, and drops the cross-sign to
// X1 even from a full chain file. The app's network security config trusts them on Android too, but it decides
// only Android's own check: .NET checks the tunnel's chain again, against the system's roots alone.
internal static class LetsEncryptRoots
